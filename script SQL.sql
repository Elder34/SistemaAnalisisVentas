
-- ============================================
-- SISTEMA DE ANALISIS DE VENTAS
-- CREACION DE TABLAS EN POSTGRESQL
-- ============================================

-- 1. ARCHIVOS PROCESADOS

CREATE TABLE IF NOT EXISTS "ArchivosProcesados" (
    id_archivo INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    nombre_archivo VARCHAR(255) NOT NULL,
    tipo_archivo VARCHAR(20) NOT NULL,
    fecha_procesamiento TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    registros_recibidos INTEGER NOT NULL DEFAULT 0,
    registros_aceptados INTEGER NOT NULL DEFAULT 0,
    registros_rechazados INTEGER NOT NULL DEFAULT 0,
    registros_duplicados INTEGER NOT NULL DEFAULT 0
);

-- 2. PRODUCTOS

CREATE TABLE IF NOT EXISTS "Productos" (
    codigo_producto VARCHAR(50) PRIMARY KEY,
    nombre_producto VARCHAR(255) NOT NULL
);

-- 3. SUCURSALES

CREATE TABLE IF NOT EXISTS "Sucursales" (
    id_sucursal INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    nombre_sucursal VARCHAR(255) NOT NULL UNIQUE,
    direccion VARCHAR(255)
);

-- 4. VENDEDORES

CREATE TABLE IF NOT EXISTS "Vendedores" (
    id_vendedor INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    codigo_vendedor VARCHAR(100) NOT NULL UNIQUE,
    nombre_vendedor VARCHAR(255) NOT NULL
);

-- 5. VENTAS

CREATE TABLE IF NOT EXISTS "Ventas" (
    id_venta VARCHAR(100) PRIMARY KEY,
    fecha DATE NOT NULL,
    id_sucursal INTEGER NOT NULL,
    codigo_producto VARCHAR(50) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL,
    monto_total NUMERIC(14, 2) NOT NULL,
    id_vendedor INTEGER NOT NULL,
    id_archivo INTEGER NOT NULL,

    CONSTRAINT fk_venta_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES "Sucursales"(id_sucursal),

    CONSTRAINT fk_venta_producto
        FOREIGN KEY (codigo_producto)
        REFERENCES "Productos"(codigo_producto),

    CONSTRAINT fk_venta_vendedor
        FOREIGN KEY (id_vendedor)
        REFERENCES "Vendedores"(id_vendedor),

    CONSTRAINT fk_venta_archivo
        FOREIGN KEY (id_archivo)
        REFERENCES "ArchivosProcesados"(id_archivo),

    CONSTRAINT chk_cantidad_positiva
        CHECK (cantidad > 0),

    CONSTRAINT chk_precio_positivo
        CHECK (precio_unitario > 0)
);

-- 6. ERRORES DE PROCESAMIENTO

CREATE TABLE IF NOT EXISTS "ErroresProcesamiento" (
    id_error INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    id_venta_origen VARCHAR(100),
    id_archivo INTEGER NOT NULL,
    numero_registro INTEGER,
    sucursal_origen VARCHAR(255),
    tipo_error VARCHAR(50) NOT NULL,
    motivo_rechazo TEXT NOT NULL,
    datos_originales TEXT,
    fecha_registro TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_error_archivo
        FOREIGN KEY (id_archivo)
        REFERENCES "ArchivosProcesados"(id_archivo)
);


